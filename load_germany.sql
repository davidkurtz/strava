		l_suffix      := initcap(j_properties.get_string('lan_type'));
		
		l_area_level  := 5;
		l_area_code   := 'LAND';
		l_area_number := l_land_id;
		l_name        := l_land;
	  ELSIF p_id = 2 THEN
--,"properties":{"geo_point_2d":{"lon":12.399114445706664,"lat":50.95641433787414},"year":"2025","lan_code":["16"],"lan_name":["Th\u00fcringen"],"krs_code":["16077"],"krs_name":["Landkreis Altenburger Land"],"krs_area_code":"DEU","krs_type":"Landkreis","krs_name_short":["Altenburger Land"]}}]}
	    l_land_id     := j_properties.get_array('lan_code').get_string(0);
		l_land        := initcap(j_properties.get_array('lan_name').get_string(0));
	    l_kreis_id    := j_properties.get_array('krs_code').get_string(0);
		l_kreis       := initcap(j_properties.get_array('krs_name_short').get_string(0));
		l_suffix      := initcap(j_properties.get_string('krs_type'));
		
		l_area_level  := 6;
		l_area_code   := 'DIS';
		l_area_number := l_kreis_id;
		l_name        := l_kreis;
	  ELSIF p_id = 3 THEN
--,"properties":{"geo_point_2d":{"lon":11.54268413185328,"lat":50.232339373533996},"year":"2025","lan_code":["09"],"lan_name":["Bayern"],"krs_code":["09477"],"krs_name":["Landkreis Kulmbach"],"vwg_code":["094770148"],"vwg_name":["Einheitsgemeinde Presseck"],"vwg_area_code":"DEU","vwg_type":"Einheitsgemeinde","vwg_name_short":["Presseck"]}}]}
	    l_land_id     := j_properties.get_array('lan_code').get_string(0);
		l_land        := initcap(j_properties.get_array('lan_name').get_string(0));
	    l_kreis_id    := j_properties.get_array('krs_code').get_string(0);
		--l_kreis       := initcap(j_properties.get_array('krs_name_short').get_string(0));
	    l_vwg_id      := j_properties.get_array('vwg_code').get_string(0);
		l_vwg         := initcap(j_properties.get_array('vwg_name_short').get_string(0));
		l_suffix      := initcap(j_properties.get_string('vwg_type'));
		
