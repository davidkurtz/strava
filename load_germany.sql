--,"properties":{"geo_point_2d":{"lon":9.616330509656812,"lat":54.46031971357786},"year":"2025","lan_code":["01"],"lan_name":["Schleswig-Holstein"],"krs_code":["01059"],"krs_name":["Kreis Schleswig-Flensburg"],"vwg_code":["010595915"],"vwg_name":["Amt Haddeby"],"gem_code":["010595915032"],"gem_name":["Gemeinde Geltorf"],"gem_area_code":"DEU","gem_type":"Gemeinde","gem_name_short":["Geltorf"]}}]}
